/*
 * event_flag.h — 任务事件旗标编号枚举
 *
 * 背景说明：
 *   服务器没有独立的"任务对象"，而是用一套「事件旗标(Event Flag)」位图机制
 *   来记录/判断任务的完成状态。每个任务对应一个事件号 N，存储在角色字段
 *   CHAR_ENDEVENT[N/32] 的第 (N%32) 位：
 *     - 判断是否完成：NPC_EventCheckFlg(char_index, N)
 *     - 标记完成：     NPC_EventSetFlg(char_index, N)
 *     - 判断进行中：   NPC_NowEventCheckFlg(char_index, N)
 *   (实现见 server/gmsv/npc/npcutil.c)
 *
 * 事件号的「权威名称」来自数据文件 data/npc/*.create 与 data/event/* 脚本
 * (本仓库未包含)，本文件仅收录源码中已硬编码、且可通过注释/上下文确认含义
 * 的事件号，便于把魔法数字替换为有意义的枚举名。
 *
 * 使用建议：
 *   1. 后续重构时，把代码里的 NPC_EventCheckFlg(idx, 63) 之类
 *      改写为 NPC_EventCheckFlg(idx, EV_HERO_BLESSING) 等。
 *   2. 若拿到 data/event 数据文件，可依据其中的任务名补齐/修正下方映射，
 *      并保持编号与实际数据文件一致。
 */

